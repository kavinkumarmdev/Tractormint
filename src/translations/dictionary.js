// Automatic Translater / Dual Resolver helper
export function resolveBilingual(inputString, targetLang = "ta") {
  if (!inputString || typeof inputString !== "string") return "";
  const clean = inputString.trim().toLowerCase();
  
  // 1. Direct match in dictionary
  if (bilingualMap[clean]) {
    return bilingualMap[clean][targetLang] || inputString;
  }
  
  // 2. Partial substring search
  for (const [key, mapping] of Object.entries(bilingualMap)) {
    if (clean.includes(key)) {
      return mapping[targetLang];
    }
  }

  // 3. Fallback: if already in Tamil and target is Tamil, keep it; if in English and target is English, keep it
  return inputString;
}
