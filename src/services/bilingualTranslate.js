/**
 * Phonetically transliterates Tamil text into English text.
 */
export function transliterateTamilToEnglish(text) {
  if (!text || typeof text !== 'string') return '';
  const trimmed = text.trim();
  const lower = trimmed.toLowerCase();

  // 1. Direct dictionary check
  if (REVERSE_AGRI_DICTIONARY[lower]) {
    return REVERSE_AGRI_DICTIONARY[lower];
  }
  if (REVERSE_AGRI_DICTIONARY[trimmed]) {
    return REVERSE_AGRI_DICTIONARY[trimmed];
  }

  // Check word by word
  const words = trimmed.split(/\s+/);
  const convertedWords = words.map(w => {
    const wLower = w.toLowerCase();
    if (REVERSE_AGRI_DICTIONARY[wLower]) {
      return REVERSE_AGRI_DICTIONARY[wLower];
    }
    if (REVERSE_AGRI_DICTIONARY[w]) {
      return REVERSE_AGRI_DICTIONARY[w];
    }

    // Single initial check (e.g. "ஏ.", "கே.", "எஸ்.", "ஆர்.")
    const initialsMap = {
      'ஏ': 'A', 'பி': 'B', 'சி': 'C', 'டி': 'D', 'இ': 'E', 'எப்': 'F',
      'ஜி': 'G', 'ஹெச்': 'H', 'ஐ': 'I', 'ஜே': 'J', 'கே': 'K', 'எல்': 'L',
      'எம்': 'M', 'என்': 'N', 'ஓ': 'O', 'பி': 'P', 'கியூ': 'Q', 'ஆர்': 'R',
      'எஸ்': 'S', 'டி': 'T', 'யு': 'U', 'வி': 'V', 'டபிள்யூ': 'W', 'எக்ஸ்': 'X',
      'ஒய்': 'Y', 'இசட்': 'Z'
    };
    const cleanInit = w.replace(/\./g, '');
    if (initialsMap[cleanInit]) {
      return `${initialsMap[cleanInit]}.`;
    }

    // Phonetic letter conversion
    let res = '';
    const chars = Array.from(w);
    for (let i = 0; i < chars.length; i++) {
      const c = chars[i];
      const next = chars[i + 1];
      const next2 = chars[i + 2];

      // Handle 'ண்ட' -> 'nd', 'த்த' -> 'th', 'ட்ட' -> 'tt'
      if (c === 'ண' && next === '்' && next2 === 'ட') {
        res += 'nd';
        i += 2;
        continue;
      }
      if (c === 'த' && next === '்' && next2 === 'த') {
        res += 'th';
        i += 2;
        continue;
      }
      if (c === 'ட' && next === '்' && next2 === 'ட') {
        res += 'tt';
        i += 2;
        continue;
      }
      if (c === 'ந' && next === '்' && next2 === 'த') {
        res += 'nth';
        i += 2;
        continue;
      }
      if (c === 'ம' && next === '்' && next2 === 'ப') {
        res += 'mb';
        i += 2;
        continue;
      }

      if (TA_VOWELS[c]) {
        res += TA_VOWELS[c];
      } else if (TA_CONSONANTS[c]) {
        const cons = TA_CONSONANTS[c];
        if (next && TA_MATRAS[next] !== undefined) {
          res += cons + TA_MATRAS[next];
          i++; // skip matra
        } else {
          // Inherent 'a' vowel unless followed by virama
          res += cons + 'a';
        }
      } else {
        res += c;
      }
    }

    // Cleanup trailing doubled vowels or awkward ends
    if (res.length > 2) {
      res = res.replace(/aa/g, 'a').replace(/ee/g, 'i').replace(/oo/g, 'u');
      if (res.endsWith('a') && res.length > 3) {
        res = res.slice(0, -1);
      }
    }
    return res.charAt(0).toUpperCase() + res.slice(1);
  });

  return convertedWords.join(' ');
}

// English to Tamil Phonetic Transliteration Rules
const EN_INITIALS_MAP = {
  'a': 'ஏ', 'b': 'பி', 'c': 'சி', 'd': 'டி', 'e': 'இ', 'f': 'எப்',
  'g': 'ஜி', 'h': 'ஹெச்', 'i': 'ஐ', 'j': 'ஜே', 'k': 'கே', 'l': 'எல்',
  'm': 'எம்', 'n': 'என்', 'o': 'ஓ', 'p': 'பி', 'q': 'கியூ', 'r': 'ஆர்',
  's': 'எஸ்', 't': 'டி', 'u': 'யு', 'v': 'வி', 'w': 'டபிள்யூ', 'x': 'எக்ஸ்',
  'y': 'ஒய்', 'z': 'இசட்'
};

/**
 * Phonetically transliterates English text into Tamil text.
 */
export function transliterateEnglishToTamil(text) {
  if (!text || typeof text !== 'string') return '';
  const trimmed = text.trim();
  const lower = trimmed.toLowerCase();

  // 1. Direct dictionary check
  if (AGRI_DICTIONARY[lower]) {
    return AGRI_DICTIONARY[lower];
  }

  // Check word by word
  const words = trimmed.split(/\s+/);
  const convertedWords = words.map(w => {
    const rawClean = w.toLowerCase().replace(/[^a-z0-9]/g, '');
    if (!rawClean) return w;

    // Check initials like "K." or "A."
    if (w.length <= 2 && EN_INITIALS_MAP[rawClean]) {
      return `${EN_INITIALS_MAP[rawClean]}.`;
    }

    if (AGRI_DICTIONARY[rawClean]) {
      return AGRI_DICTIONARY[rawClean];
    }

    // Heuristics for common suffixes
    if (rawClean.endsWith('kumar') && rawClean.length > 5) {
      const prefix = rawClean.replace('kumar', '');
      const preTa = AGRI_DICTIONARY[prefix] || transliterateEnglishToTamil(prefix);
      return `${preTa} குமார்`.trim();
    }
    if (rawClean.endsWith('samy') && rawClean.length > 4) {
      const prefix = rawClean.replace('samy', '');
      const preTa = AGRI_DICTIONARY[prefix] || transliterateEnglishToTamil(prefix);
      return `${preTa}சாமி`.trim();
    }
    if (rawClean.endsWith('swamy') && rawClean.length > 5) {
      const prefix = rawClean.replace('swamy', '');
      const preTa = AGRI_DICTIONARY[prefix] || transliterateEnglishToTamil(prefix);
      return `${preTa}சாமி`.trim();
    }

    // Letter-by-letter phonetic conversion
    let out = '';
    let i = 0;
    const len = rawClean.length;
    while (i < len) {
      const isEnd = (i === len - 1);
      const sub2 = rawClean.slice(i, i + 2);
      const sub3 = rawClean.slice(i, i + 3);

      if (sub3 === 'nth') { out += 'ந்த'; i += 3; continue; }
      if (sub2 === 'th') { out += (isEnd ? 'த்' : 'த'); i += 2; continue; }
      if (sub2 === 'sh') { out += (isEnd ? 'ஷ்' : 'ஷ'); i += 2; continue; }
      if (sub2 === 'ch') { out += (isEnd ? 'ச்' : 'ச'); i += 2; continue; }
      if (sub2 === 'zh') { out += (isEnd ? 'ழ்' : 'ழ'); i += 2; continue; }
      if (sub2 === 'aa') { out += 'ா'; i += 2; continue; }
      if (sub2 === 'ee') { out += 'ீ'; i += 2; continue; }
      if (sub2 === 'oo') { out += 'ூ'; i += 2; continue; }
      if (sub2 === 'ai') { out += 'ை'; i += 2; continue; }
      if (sub2 === 'nd') { out += 'ண்ட'; i += 2; continue; }
      if (sub2 === 'mb') { out += 'ம்ப'; i += 2; continue; }

      const char = rawClean[i];
      switch (char) {
        case 'a':
          out += (out ? (i > 1 ? 'ா' : '') : 'அ');
          break;
        case 'e': out += (out ? 'ெ' : 'எ'); break;
        case 'i': out += (out ? 'ி' : 'இ'); break;
        case 'o': out += (out ? 'ொ' : 'ஒ'); break;
        case 'u': out += (out ? 'ு' : 'உ'); break;
        case 'k': case 'c': case 'g':
          out += (isEnd ? 'க்' : 'க');
          break;
        case 's':
          out += (isEnd ? 'ஸ்' : 'ச');
          break;
        case 't': case 'd':
          out += (isEnd ? 'ட்' : 'ட');
          break;
        case 'p': case 'b': case 'f':
          out += (isEnd ? 'ப்' : 'ப');
          break;
        case 'm':
          out += (isEnd ? 'ம்' : 'ம');
          break;
        case 'n':
          out += (isEnd ? 'ன்' : 'ன');
          break;
        case 'r':
          out += (isEnd ? 'ர்' : 'ர');
          break;
        case 'l':
          out += (isEnd ? 'ல்' : 'ல');
          break;
        case 'v': case 'w':
          out += (isEnd ? 'வ்' : 'வ');
          break;
        case 'y':
          out += (isEnd ? 'ய்' : 'ய');
          break;
        case 'j':
          out += (isEnd ? 'ஜ்' : 'ஜ');
          break;
        default:
          out += char;
          break;
      }
      i++;
    }
    return out || w;
  });

  return convertedWords.join(' ');
}

/**
 * Detects whether the input string is predominantly Tamil script.
 */
export function isTamilScript(text) {
  if (!text) return false;
  // Tamil Unicode block: \u0B80-\u0BFF
  const tamilRegex = /[\u0B80-\u0BFF]/g;
  const matches = text.match(tamilRegex);
  return matches && matches.length > 0;
}

/**
 * Automatically calculates the counterpart language value (En <-> Ta)
 * using local dictionary, phonetics, and optional online API.
 */
export async function autoFillCounterpart({ text, sourceLang = 'auto' }) {
  if (!text || !text.trim()) {
    return { english: '', tamil: '' };
  }

  const trimmed = text.trim();
  const isTamil = sourceLang === 'ta' || (sourceLang === 'auto' && isTamilScript(trimmed));

  if (isTamil) {
    // Input is Tamil -> Derive English
    const localEn = transliterateTamilToEnglish(trimmed);
    
    // Attempt online translation if available
    try {
      if (navigator.onLine) {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 1800);
        const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(trimmed)}&langpair=ta|en`;
        const res = await fetch(url, { signal: controller.signal });
        clearTimeout(timeoutId);
        if (res.ok) {
          const data = await res.json();
          if (data && data.responseData && data.responseData.translatedText) {
            const apiResult = data.responseData.translatedText.trim();
            // Don't use if it just repeated the same untranslated text or error
            if (apiResult && !isTamilScript(apiResult) && !apiResult.toLowerCase().includes('quota')) {
              return { english: apiResult, tamil: trimmed };
            }
          }
        }
      }
    } catch {
      // Gracefully fall back to local transliteration
    }

    return { english: localEn || trimmed, tamil: trimmed };
  } else {
    // Input is English -> Derive Tamil
    const localTa = transliterateEnglishToTamil(trimmed);

    // Attempt online translation if available
    try {
      if (navigator.onLine) {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 1800);
        const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(trimmed)}&langpair=en|ta`;
        const res = await fetch(url, { signal: controller.signal });
        clearTimeout(timeoutId);
        if (res.ok) {
          const data = await res.json();
          if (data && data.responseData && data.responseData.translatedText) {
            const apiResult = data.responseData.translatedText.trim();
            if (apiResult && isTamilScript(apiResult) && !apiResult.toLowerCase().includes('quota')) {
              return { english: trimmed, tamil: apiResult };
            }
          }
        }
      }
    } catch {
      // Gracefully fall back to local transliteration
    }

    return { english: trimmed, tamil: localTa || trimmed };
  }
}

/**
 * Converts speech recognition transcripts into numeric digits for mobile numbers.
 * Supports both Tamil and English spoken numbers, single digits, repeated numbers ("double 9"),
 * and direct digit streams.
 */
export function parseSpokenPhoneDigits(text) {
  if (!text || typeof text !== 'string') return '';

  const clean = text.toLowerCase().trim();

  // Word-to-digit dictionary
  const DIGIT_WORDS = {
    // English single digits
    'zero': '0', 'oh': '0', 'o': '0', 'null': '0',
    'one': '1', 'won': '1',
    'two': '2', 'to': '2', 'too': '2',
    'three': '3', 'tree': '3',
    'four': '4', 'for': '4', 'fore': '4',
    'five': '5',
    'six': '6',
    'seven': '7',
    'eight': '8', 'ate': '8',
    'nine': '9', 'niner': '9',

    // English teens and tens
    'ten': '10', 'eleven': '11', 'twelve': '12', 'thirteen': '13',
    'fourteen': '14', 'fifteen': '15', 'sixteen': '16', 'seventeen': '17',
    'eighteen': '18', 'nineteen': '19',
    'twenty': '20', 'thirty': '30', 'forty': '40', 'fifty': '50',
    'sixty': '60', 'seventy': '70', 'eighty': '80', 'ninety': '90',

    // Tamil single digits (colloquial and formal)
    'பூஜ்ஜியம்': '0', 'பூஜ்யம்': '0', 'சைபர்': '0', 'ஜீரோ': '0',
    'ஒன்று': '1', 'ஒன்னு': '1', 'ஒரு': '1', 'ஒன்ன': '1',
    'இரண்டு': '2', 'ரெண்டு': '2', 'ரெண்ட': '2',
    'மூன்று': '3', 'மூணு': '3', 'மூண': '3',
    'நான்கு': '4', 'நாலு': '4', 'நாலா': '4',
    'ஐந்து': '5', 'அஞ்சு': '5', 'அஞ்ச': '5',
    'ஆறு': '6', 'ஆற': '6',
    'ஏழு': '7', 'ஏழ': '7',
    'எட்டு': '8', 'எட்ட': '8',
    'ஒன்பது': '9', 'ஒம்போது': '9', 'ஒம்பது': '9', 'ஒன்பதாவது': '9',

    // Tamil tens
    'பத்து': '10', 'இருபது': '20', 'முப்பது': '30', 'நாற்பது': '40',
    'ஐம்பது': '50', 'அறுபது': '60', 'எழுபது': '70', 'எண்பது': '80', 'தொண்ணூறு': '90'
  };

  // Split by whitespace, punctuation, commas, hyphens
  const tokens = clean.split(/[\s,.-]+/);
  let result = '';
  let repeatCount = 1;

  for (let i = 0; i < tokens.length; i++) {
    const rawToken = tokens[i].trim();
    if (!rawToken) continue;

    // Check for double / triple modifiers
    if (rawToken === 'double' || rawToken === 'டபுள்' || rawToken === 'இரட்டை') {
      repeatCount = 2;
      continue;
    }
    if (rawToken === 'triple' || rawToken === 'ட்ரிபிள்' || rawToken === 'மும்முறை') {
      repeatCount = 3;
      continue;
    }

    // Direct numeric match in token (e.g. "98421" or "9")
    if (/^\d+$/.test(rawToken)) {
      if (repeatCount > 1) {
        const firstDigit = rawToken[0];
        result += firstDigit.repeat(repeatCount) + rawToken.slice(1);
      } else {
        result += rawToken;
      }
      repeatCount = 1;
      continue;
    }

    // Check dictionary
    if (DIGIT_WORDS[rawToken] !== undefined) {
      const mapped = DIGIT_WORDS[rawToken];
      if (repeatCount > 1 && mapped.length === 1) {
        result += mapped.repeat(repeatCount);
      } else {
        result += mapped;
      }
      repeatCount = 1;
      continue;
    }

    // If token has digits embedded with letters, extract any numbers
    const embeddedDigits = rawToken.replace(/\D/g, '');
    if (embeddedDigits) {
      result += embeddedDigits;
      repeatCount = 1;
    }
  }

  // Remove any remaining non-digit characters and limit to 10 digits
  return result.replace(/\D/g, '').slice(0, 10);
}
