const TA_MATRAS = {
  'ா': 'aa', 'ி': 'i', 'ீ': 'ee', 'ு': 'u', 'ூ': 'oo',
  'ெ': 'e', 'ே': 'ae', 'ை': 'ai', 'ொ': 'o', 'ோ': 'oa', 'ௌ': 'au',
  '்': '' // pulli (virama)
};

/**
 * Phonetically transliterates Tamil text into English text.
 */
export function transliterateTamilToEnglish(text) {
  if (!text || typeof text !== 'string') return '';
  const trimmed = text.trim();
  const lower = trimmed.toLowerCase();

  // 1. Direct dictionary check
  if (REVERSE_AGRI_DICTIONARY[lower]) {
    return REVERSE_AGRI_DICTIONARY[lower];
  }

  // Check word by word
  const words = trimmed.split(/\s+/);
  const convertedWords = words.map(w => {
    const wLower = w.toLowerCase();
    if (REVERSE_AGRI_DICTIONARY[wLower]) {
      return REVERSE_AGRI_DICTIONARY[wLower];
    }

    // Phonetic letter conversion
    let res = '';
    const chars = Array.from(w);
    for (let i = 0; i < chars.length; i++) {
      const c = chars[i];
      const next = chars[i + 1];

      if (TA_VOWELS[c]) {
        res += TA_VOWELS[c];
      } else if (TA_CONSONANTS[c]) {
        const cons = TA_CONSONANTS[c];
        if (next && TA_MATRAS[next] !== undefined) {
          res += cons + TA_MATRAS[next];
          i++; // skip matra
        } else {
          // Inherent 'a' vowel unless followed by virama
          res += cons + 'a';
        }
      } else {
        res += c;
      }
    }
    // Clean up trailing 'a' if common name end, e.g. murugana -> murugan
    if (res.endsWith('a') && res.length > 3) {
      // gentle cleanup
    }
    return res.charAt(0).toUpperCase() + res.slice(1);
  });

  return convertedWords.join(' ');
}

