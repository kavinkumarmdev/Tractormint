/**
 * Phonetically transliterates English text into Tamil text.
 */
export function transliterateEnglishToTamil(text) {
  if (!text || typeof text !== 'string') return '';
  const trimmed = text.trim();
  const lower = trimmed.toLowerCase();

  // 1. Direct dictionary check
  if (AGRI_DICTIONARY[lower]) {
    return AGRI_DICTIONARY[lower];
  }

  // Check word by word
  const words = trimmed.split(/\s+/);
  const convertedWords = words.map(w => {
    const wLower = w.toLowerCase().replace(/[^a-z0-9]/g, '');
    if (AGRI_DICTIONARY[wLower]) {
      return AGRI_DICTIONARY[wLower];
    }

    // Phonetic heuristic for names / words
    let mapped = wLower;
    // Handle specific common names
    if (AGRI_DICTIONARY[wLower]) return AGRI_DICTIONARY[wLower];

    // Simple rule-based phonetics
    let out = '';
    let i = 0;
    while (i < wLower.length) {
      const sub2 = wLower.slice(i, i + 2);
      if (sub2 === 'th') { out += 'த'; i += 2; continue; }
      if (sub2 === 'sh') { out += 'ஷ'; i += 2; continue; }
      if (sub2 === 'ch') { out += 'ச'; i += 2; continue; }
      if (sub2 === 'zh') { out += 'ழ'; i += 2; continue; }
      if (sub2 === 'aa') { out += 'ா'; i += 2; continue; }
      if (sub2 === 'ee') { out += 'ீ'; i += 2; continue; }
      if (sub2 === 'oo') { out += 'ூ'; i += 2; continue; }
      if (sub2 === 'ai') { out += 'ை'; i += 2; continue; }

      const char = wLower[i];
      switch (char) {
        case 'a': out += out ? 'ா' : 'அ'; break;
        case 'e': out += out ? 'ெ' : 'எ'; break;
        case 'i': out += out ? 'ி' : 'இ'; break;
        case 'o': out += out ? 'ொ' : 'ஒ'; break;
        case 'u': out += out ? 'ு' : 'உ'; break;
        case 'k': case 'c': case 'g': out += 'க'; break;
        case 's': out += 'ச'; break;
        case 't': case 'd': out += 'ட'; break;
        case 'p': case 'b': case 'f': out += 'ப'; break;
        case 'm': out += 'ம'; break;
        case 'n': out += 'ன'; break;
        case 'r': out += 'ர'; break;
        case 'l': out += 'ல'; break;
        case 'v': case 'w': out += 'வ'; break;
        case 'y': out += 'ய'; break;
        case 'j': out += 'ஜ'; break;
        default: out += char; break;
      }
      i++;
    }
    return out || w;
  });

  return convertedWords.join(' ');
}

/**
 * Detects whether the input string is predominantly Tamil script.
 */
export function isTamilScript(text) {
  if (!text) return false;
  // Tamil Unicode block: \u0B80-\u0BFF
  const tamilRegex = /[\u0B80-\u0BFF]/g;
  const matches = text.match(tamilRegex);
  return matches && matches.length > 0;
}

/**
 * Automatically calculates the counterpart language value (En <-> Ta)
 * using local dictionary, phonetics, and optional online API.
 */
export async function autoFillCounterpart({ text, sourceLang = 'auto' }) {
  if (!text || !text.trim()) {
    return { english: '', tamil: '' };
  }

  const trimmed = text.trim();
  const isTamil = sourceLang === 'ta' || (sourceLang === 'auto' && isTamilScript(trimmed));

  if (isTamil) {
    // Input is Tamil -> Derive English
    const localEn = transliterateTamilToEnglish(trimmed);
    
    // Attempt online translation if available
    try {
      if (navigator.onLine) {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 1800);
        const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(trimmed)}&langpair=ta|en`;
        const res = await fetch(url, { signal: controller.signal });
        clearTimeout(timeoutId);
        if (res.ok) {
          const data = await res.json();
          if (data && data.responseData && data.responseData.translatedText) {
            const apiResult = data.responseData.translatedText.trim();
            // Don't use if it just repeated the same untranslated text or error
            if (apiResult && !isTamilScript(apiResult) && !apiResult.toLowerCase().includes('quota')) {
              return { english: apiResult, tamil: trimmed };
            }
          }
        }
      }
    } catch {
      // Gracefully fall back to local transliteration
    }

    return { english: localEn || trimmed, tamil: trimmed };
  } else {
    // Input is English -> Derive Tamil
    const localTa = transliterateEnglishToTamil(trimmed);

    // Attempt online translation if available
    try {
      if (navigator.onLine) {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 1800);
        const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(trimmed)}&langpair=en|ta`;
        const res = await fetch(url, { signal: controller.signal });
        clearTimeout(timeoutId);
        if (res.ok) {
          const data = await res.json();
          if (data && data.responseData && data.responseData.translatedText) {
            const apiResult = data.responseData.translatedText.trim();
            if (apiResult && isTamilScript(apiResult) && !apiResult.toLowerCase().includes('quota')) {
              return { english: trimmed, tamil: apiResult };
            }
          }
        }
      }
    } catch {
      // Gracefully fall back to local transliteration
    }

    return { english: trimmed, tamil: localTa || trimmed };
  }
}

